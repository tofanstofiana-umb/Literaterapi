import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const preparedRoot = path.join(root, "content-prepared");
const publicRoot = path.join(root, "public", "assets", "stories");
const generatedPath = path.join(root, "src", "content", "stories.generated.ts");

function readJson(filePath) {
  return JSON.parse(readFileSync(filePath, "utf8"));
}

function toPublicPath(filePath) {
  return `/${path.relative(path.join(root, "public"), filePath).replaceAll(path.sep, "/")}`;
}

function isInstructionalParagraph(paragraph) {
  const text = paragraph.trim();
  return (
    /^Narator:/i.test(text) ||
    /^Mari isi tabel/i.test(text) ||
    /Isilah tabel berikut/i.test(text) ||
    /sudah mengisi tabel/i.test(text) ||
    /Ucapkan kalimat berikut/i.test(text) ||
    /^"Saya membuka diri/i.test(text) ||
    /^"Dengan penuh perhatian/i.test(text) ||
    /^"Mempelajari/i.test(text)
  );
}

function parseStoryMarkdown(markdown) {
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  const titleLine = lines.find((line) => line.startsWith("# ")) ?? "# Cerita";
  const title = titleLine.replace(/^#\s+/, "").trim();
  const subtitleLine = lines.find((line) => line.startsWith("_") && line.endsWith("_"));
  const subtitle = subtitleLine ? subtitleLine.replace(/^_/, "").replace(/_$/, "").trim() : "";

  const paragraphs = [];
  let buffer = [];
  const flushBuffer = () => {
    if (!buffer.length) return;
    const paragraph = buffer.join(" ").trim();
    if (paragraph && !isInstructionalParagraph(paragraph)) {
      paragraphs.push(paragraph);
    }
    buffer = [];
  };

  for (const line of lines) {
    if (line.startsWith("# ")) continue;
    if (subtitleLine && line === subtitleLine) continue;
    if (!line.trim()) {
      flushBuffer();
      continue;
    }
    buffer.push(line.trim());
  }
  flushBuffer();

  const notesIndex = paragraphs.findIndex((paragraph) => /^Catatan untuk Pembaca$/i.test(paragraph));
  const cleanParagraphs = notesIndex >= 0 ? paragraphs.slice(0, notesIndex) : paragraphs;

  return { title, subtitle, paragraphs: cleanParagraphs };
}

function copyAsset(source, destination) {
  mkdirSync(path.dirname(destination), { recursive: true });
  copyFileSync(source, destination);
}

function buildExcerpt(paragraphs) {
  const text = paragraphs.join(" ");
  return text.length > 180 ? `${text.slice(0, 177).trim()}...` : text;
}

const index = readJson(path.join(preparedRoot, "stories.index.json"));
rmSync(publicRoot, { recursive: true, force: true });
mkdirSync(publicRoot, { recursive: true });
mkdirSync(path.dirname(generatedPath), { recursive: true });

const stories = index.stories.map((entry) => {
  const folder = path.join(root, entry.folder);
  const metadata = readJson(path.join(folder, "metadata.json"));
  const storyMarkdown = readFileSync(path.join(folder, "story.md"), "utf8");
  const parsed = parseStoryMarkdown(storyMarkdown);
  const assetFolder = path.join(publicRoot, metadata.slug);
  const illustrations = [];

  let coverUrl = "";
  if (metadata.coverImage) {
    const source = path.join(folder, metadata.coverImage);
    const destination = path.join(assetFolder, "cover.png");
    if (existsSync(source)) {
      copyAsset(source, destination);
      coverUrl = toPublicPath(destination);
    }
  }

  for (const relative of metadata.illustrations ?? []) {
    const source = path.join(folder, relative);
    if (!existsSync(source)) continue;
    const filename = path.basename(relative);
    const destination = path.join(assetFolder, "illustrations", filename);
    copyAsset(source, destination);
    illustrations.push({
      src: toPublicPath(destination),
      alt: `Ilustrasi adegan dari cerpen ${metadata.title}`,
      source: relative,
    });
  }

  return {
    slug: metadata.slug,
    title: metadata.title,
    subtitle: parsed.subtitle,
    excerpt: buildExcerpt(parsed.paragraphs),
    originCountry: metadata.originCountry,
    originalLanguage: metadata.originalLanguage,
    readingEstimateMinutes: metadata.readingEstimateMinutes,
    cleanWordCount: metadata.cleanWordCount,
    emotionalIntensity: metadata.emotionalIntensity,
    facilitatorRequirement: metadata.facilitatorRequirement,
    internalCategory: metadata.internalCategoryGuess,
    publicCategorySlugs: metadata.publicCategorySlugs ?? [],
    coverUrl,
    illustrations,
    paragraphs: parsed.paragraphs,
  };
});

const output = `// This file is generated by scripts/generate-content.mjs.
// Do not edit by hand; update content-prepared and regenerate instead.

export const STORY_CATEGORY_LABELS = {
  "menemukan-ketenangan": "Menemukan Ketenangan",
  "menemukan-harapan": "Menemukan Harapan",
  "mengelola-emosi": "Mengelola Emosi",
  "menemukan-cara-belajar": "Menemukan Cara Belajar",
  "menghargai-diri": "Menghargai Diri",
  "berani-menghadapi-tekanan": "Berani Menghadapi Tekanan",
  "membangun-pertemanan-sehat": "Membangun Pertemanan Sehat",
  "mendengarkan-tubuh": "Mendengarkan Tubuh",
  "mencari-pegangan": "Mencari Pegangan",
  "meminta-bantuan": "Meminta Bantuan",
} as const;

export type StoryCategorySlug = keyof typeof STORY_CATEGORY_LABELS;

export type StoryOriginCountry = "Indonesia" | "Malaysia";

export interface StoryIllustration {
  src: string;
  alt: string;
  source: string;
}

export interface PreparedStory {
  slug: string;
  title: string;
  subtitle: string;
  excerpt: string;
  originCountry: StoryOriginCountry;
  originalLanguage: "id-ID" | "ms-MY";
  readingEstimateMinutes: number;
  cleanWordCount: number;
  emotionalIntensity: "low" | "medium" | "high";
  facilitatorRequirement: "independent" | "recommended" | "required" | "restricted";
  internalCategory: string;
  publicCategorySlugs: StoryCategorySlug[];
  coverUrl: string;
  illustrations: StoryIllustration[];
  paragraphs: string[];
}

export const STORIES = ${JSON.stringify(stories, null, 2)} as PreparedStory[];
`;

writeFileSync(generatedPath, output, "utf8");
console.log(`Generated ${stories.length} stories`);
console.log(`Wrote ${path.relative(root, generatedPath)}`);
console.log(`Copied assets to ${path.relative(root, publicRoot)}`);
